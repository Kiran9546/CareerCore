"""
CareerCore — Synthetic Student Profile Dataset Generator
=========================================================

Generates labelled (student profile -> career path) training data for the
Random Forest career prediction model described in Phase 1 Section 4.2.1.

METHODOLOGY
-----------
Labelled student-profile-to-placement-outcome data is not publicly available at
the granularity this system requires (Phase 1 Constraint 3.3). This generator
therefore synthesises profiles from documented career archetype distributions.

For each career path, a student's probability of holding skill i is derived from
that skill's importance weight w_i in careerPaths.json:

        P(holds skill i) = clip(BASE + SLOPE * w_i, 0.02, 0.95)

Skills OUTSIDE the target archetype are sampled at a low background rate, and a
"cross-domain bleed" term raises that rate for skills shared with adjacent
archetypes. This is what prevents the classes from being trivially separable.

AMBIGUITY INJECTION
-------------------
AMBIGUOUS_FRACTION of profiles are generated by blending two ADJACENT archetypes
(e.g. Software Engineer / Web Developer) at a random mixing ratio, then labelled
with the dominant one. This is deliberate: a cleanly separable synthetic dataset
yields ~99% test accuracy, which is neither credible nor generalisable.

EDGE CASES
----------
A configurable share of profiles are drawn from realistic edge-case templates
(theory-strong/practice-weak, self-taught, certificate-collector, sparse) so the
downstream system is exercised against the profiles it will actually meet.

Reproducible via RANDOM_SEED.

Usage:
    python generate_dataset.py
    python generate_dataset.py --n 8000 --out ../data/train.csv
"""

import argparse
import json
import os
import numpy as np
import pandas as pd

# ----------------------------------------------------------------------------
# CONFIGURATION
# ----------------------------------------------------------------------------

RANDOM_SEED = 42

N_SAMPLES = 5000
AMBIGUOUS_FRACTION = 0.15      # blended two-archetype profiles
EDGE_CASE_FRACTION = 0.08      # realistic outlier profiles

# P(holds skill) = BASE + SLOPE * weight     for in-archetype skills
SKILL_BASE = 0.08
SKILL_SLOPE = 0.80

BACKGROUND_SKILL_PROB = 0.04   # unrelated skills
BLEED_SKILL_PROB = 0.22        # skills belonging to an adjacent archetype

PROFICIENCY_MEAN_SLOPE = 2.2   # higher-weight skills get higher proficiency
PROFICIENCY_BASE = 2.3

# Archetypes that genuinely overlap in the real world. Used both for
# cross-domain bleed and for generating ambiguous samples.
ADJACENCY = {
    "Software Engineer":     ["Web Developer", "QA Engineer"],
    "Web Developer":         ["Software Engineer"],
    "Data Analyst":          ["ML Engineer"],
    "ML Engineer":           ["Data Analyst", "Software Engineer"],
    "DevOps Engineer":       ["Cloud Engineer"],
    "Cloud Engineer":        ["DevOps Engineer", "Cybersecurity Analyst"],
    "Cybersecurity Analyst": ["Cloud Engineer"],
    "QA Engineer":           ["Software Engineer"],
}

# Per-archetype academic / aptitude profile.
# aptitude entries are (mean, std) out of 100 for (quant, logical, verbal, technical)
ARCHETYPE_STATS = {
    "Software Engineer":     {"cgpa": (7.8, 0.8), "apt": [(72, 12), (74, 11), (66, 13), (75, 11)],
                              "projects": (3.0, 1.2), "certs": (2.2, 1.4)},
    "Web Developer":         {"cgpa": (7.3, 0.9), "apt": [(64, 13), (67, 12), (66, 12), (70, 12)],
                              "projects": (3.8, 1.4), "certs": (2.6, 1.5)},
    "Data Analyst":          {"cgpa": (7.9, 0.8), "apt": [(78, 10), (74, 11), (70, 12), (68, 12)],
                              "projects": (2.6, 1.1), "certs": (3.1, 1.5)},
    "ML Engineer":           {"cgpa": (8.3, 0.7), "apt": [(82, 9),  (79, 10), (69, 12), (76, 11)],
                              "projects": (3.2, 1.3), "certs": (3.4, 1.6)},
    "DevOps Engineer":       {"cgpa": (7.4, 0.9), "apt": [(70, 12), (73, 11), (64, 13), (78, 10)],
                              "projects": (2.8, 1.2), "certs": (3.0, 1.5)},
    "Cloud Engineer":        {"cgpa": (7.5, 0.9), "apt": [(71, 12), (72, 11), (66, 12), (77, 10)],
                              "projects": (2.5, 1.1), "certs": (3.6, 1.6)},
    "Cybersecurity Analyst": {"cgpa": (7.6, 0.9), "apt": [(73, 11), (77, 10), (67, 12), (76, 11)],
                              "projects": (2.4, 1.1), "certs": (3.3, 1.6)},
    "QA Engineer":           {"cgpa": (7.1, 0.9), "apt": [(65, 13), (70, 12), (68, 12), (66, 12)],
                              "projects": (2.2, 1.0), "certs": (2.4, 1.4)},
}

BRANCHES = ["ISE", "CSE", "ECE", "EEE", "MECH", "CIVIL", "AIML"]
BRANCH_WEIGHTS = [0.28, 0.32, 0.16, 0.08, 0.08, 0.04, 0.04]


# ----------------------------------------------------------------------------
# LOADERS
# ----------------------------------------------------------------------------

def load_seed(seed_dir):
    """Load the skill taxonomy and career path definitions."""
    with open(os.path.join(seed_dir, "skills.json")) as f:
        skills = json.load(f)
    with open(os.path.join(seed_dir, "careerPaths.json")) as f:
        paths = json.load(f)

    skill_names = [s["name"] for s in skills]
    skill_index = {n: i for i, n in enumerate(skill_names)}

    # weight vector per archetype, aligned to skill_names
    path_weights = {}
    for p in paths:
        vec = np.zeros(len(skill_names))
        for rs in p["requiredSkills"]:
            vec[skill_index[rs["skill"]]] = rs["weight"]
        path_weights[p["name"]] = vec

    return skill_names, skill_index, path_weights, paths


# ----------------------------------------------------------------------------
# PROFILE GENERATION
# ----------------------------------------------------------------------------

def skill_probabilities(weight_vec, bleed_vec):
    """
    Convert an archetype weight vector into per-skill holding probabilities.

    In-archetype skills scale with their importance weight. Skills belonging to
    an adjacent archetype get an elevated background rate (the "bleed"), and
    everything else sits at a low baseline.
    """
    p = np.full(weight_vec.shape, BACKGROUND_SKILL_PROB)
    p = np.where(bleed_vec > 0, BLEED_SKILL_PROB, p)
    in_arch = weight_vec > 0
    p[in_arch] = SKILL_BASE + SKILL_SLOPE * weight_vec[in_arch]
    return np.clip(p, 0.02, 0.95)


def sample_skills(rng, weight_vec, bleed_vec, skill_multiplier=1.0):
    """
    Sample a proficiency vector in [0, 1] (proficiency/5, per Blueprint 5.4).
    Returns zeros for skills the student does not hold.
    """
    probs = skill_probabilities(weight_vec, bleed_vec) * skill_multiplier
    probs = np.clip(probs, 0.0, 0.97)
    held = rng.random(len(probs)) < probs

    # proficiency 1-5, correlated with importance weight
    mean_prof = PROFICIENCY_BASE + PROFICIENCY_MEAN_SLOPE * weight_vec
    prof = rng.normal(mean_prof, 1.0)
    prof = np.clip(np.round(prof), 1, 5)

    return np.where(held, prof / 5.0, 0.0)


def build_bleed_vector(archetype, path_weights):
    """Union of skill sets belonging to archetypes adjacent to this one."""
    bleed = np.zeros_like(path_weights[archetype])
    for neighbour in ADJACENCY.get(archetype, []):
        bleed = np.maximum(bleed, (path_weights[neighbour] > 0).astype(float))
    bleed[path_weights[archetype] > 0] = 0.0   # in-archetype takes precedence
    return bleed


def sample_academics(rng, archetype, edge_case=None):
    """CGPA, backlogs, aptitude sections, project and certification counts."""
    st = ARCHETYPE_STATS[archetype]

    cgpa = float(np.clip(rng.normal(*st["cgpa"]), 5.0, 10.0))
    apt = [float(np.clip(rng.normal(m, s), 20, 100)) for m, s in st["apt"]]
    n_proj = int(np.clip(round(rng.normal(*st["projects"])), 0, 8))
    n_cert = int(np.clip(round(rng.normal(*st["certs"])), 0, 9))

    # backlogs inversely related to CGPA
    backlog_lam = max(0.0, (7.5 - cgpa) * 0.9)
    backlogs = int(np.clip(rng.poisson(backlog_lam), 0, 8))

    if edge_case == "theory_strong":
        cgpa = float(np.clip(rng.normal(9.0, 0.4), 8.2, 10.0))
        backlogs = 0
        n_proj = int(rng.integers(0, 2))
        apt = [min(100, a + 8) for a in apt]
    elif edge_case == "self_taught":
        cgpa = float(np.clip(rng.normal(6.3, 0.6), 5.0, 7.2))
        backlogs = int(rng.integers(0, 4))
        n_proj = int(rng.integers(5, 9))
    elif edge_case == "cert_collector":
        n_cert = int(rng.integers(6, 10))
        n_proj = int(rng.integers(0, 2))
    elif edge_case == "sparse":
        n_proj = 0
        n_cert = 0
        apt = [0.0, 0.0, 0.0, 0.0]      # aptitude test not attempted

    return cgpa, backlogs, apt, n_proj, n_cert


EDGE_CASE_TYPES = ["theory_strong", "self_taught", "cert_collector", "sparse"]
EDGE_CASE_PROBS = [0.30, 0.30, 0.25, 0.15]


def generate(n_samples, seed_dir, seed=RANDOM_SEED):
    rng = np.random.default_rng(seed)
    skill_names, skill_index, path_weights, paths = load_seed(seed_dir)
    archetypes = list(path_weights.keys())

    bleed_vectors = {a: build_bleed_vector(a, path_weights) for a in archetypes}

    n_per = n_samples // len(archetypes)
    rows = []

    for archetype in archetypes:
        for _ in range(n_per):
            is_ambiguous = rng.random() < AMBIGUOUS_FRACTION
            edge_case = None
            if rng.random() < EDGE_CASE_FRACTION:
                edge_case = rng.choice(EDGE_CASE_TYPES, p=EDGE_CASE_PROBS)

            if is_ambiguous and ADJACENCY.get(archetype):
                # blend with an adjacent archetype; label stays dominant
                other = rng.choice(ADJACENCY[archetype])
                ratio = rng.uniform(0.55, 0.75)          # dominance of the label class
                w = ratio * path_weights[archetype] + (1 - ratio) * path_weights[other]
                bleed = np.maximum(bleed_vectors[archetype], bleed_vectors[other])
            else:
                w = path_weights[archetype]
                bleed = bleed_vectors[archetype]

            mult = 0.55 if edge_case in ("theory_strong", "cert_collector") else 1.0
            if edge_case == "sparse":
                mult = 0.25
            if edge_case == "self_taught":
                mult = 1.25

            skill_vec = sample_skills(rng, w, bleed, skill_multiplier=mult)
            cgpa, backlogs, apt, n_proj, n_cert = sample_academics(rng, archetype, edge_case)

            row = {
                "cgpa": round(cgpa, 2),
                "backlogs": backlogs,
                "apt_quantitative": round(apt[0], 1),
                "apt_logical": round(apt[1], 1),
                "apt_verbal": round(apt[2], 1),
                "apt_technical": round(apt[3], 1),
                "num_projects": n_proj,
                "num_certifications": n_cert,
                "branch": rng.choice(BRANCHES, p=BRANCH_WEIGHTS),
                "is_ambiguous": int(is_ambiguous),
                "edge_case": edge_case if edge_case else "none",
            }
            for i, name in enumerate(skill_names):
                row[f"skill_{name}"] = round(float(skill_vec[i]), 2)
            row["career_path"] = archetype
            rows.append(row)

    df = pd.DataFrame(rows).sample(frac=1.0, random_state=seed).reset_index(drop=True)
    return df, skill_names


# ----------------------------------------------------------------------------
# REPORTING
# ----------------------------------------------------------------------------

def report(df, skill_names):
    print("=" * 68)
    print("DATASET SUMMARY")
    print("=" * 68)
    print(f"Rows           : {len(df)}")
    print(f"Feature columns: {len(df.columns) - 1}")
    print(f"  numeric      : 8 (cgpa, backlogs, 4x aptitude, projects, certs)")
    print(f"  skill columns: {len(skill_names)}")
    print(f"Classes        : {df['career_path'].nunique()}")
    print()

    print("CLASS BALANCE")
    for cls, cnt in df["career_path"].value_counts().sort_index().items():
        bar = "#" * int(cnt / 12)
        print(f"  {cls:<24}{cnt:>5}  {bar}")
    print()

    print("NOISE INJECTION")
    amb = df["is_ambiguous"].mean()
    print(f"  Ambiguous (blended) profiles : {amb:6.1%}   [target {AMBIGUOUS_FRACTION:.0%}]")
    ec = df[df["edge_case"] != "none"]
    print(f"  Edge-case profiles           : {len(ec)/len(df):6.1%}   [target {EDGE_CASE_FRACTION:.0%}]")
    for k, v in df["edge_case"].value_counts().items():
        if k != "none":
            print(f"      {k:<22}{v:>5}")
    print()

    print("NUMERIC FEATURE RANGES")
    for c in ["cgpa", "backlogs", "apt_quantitative", "apt_logical",
              "apt_verbal", "apt_technical", "num_projects", "num_certifications"]:
        print(f"  {c:<22} min={df[c].min():>6.2f}  mean={df[c].mean():>6.2f}  max={df[c].max():>6.2f}")
    print()

    scols = [c for c in df.columns if c.startswith("skill_")]
    held = (df[scols] > 0).sum(axis=1)
    print("SKILL DENSITY (skills held per student)")
    print(f"  min={held.min()}  mean={held.mean():.1f}  median={held.median():.0f}  max={held.max()}")
    print()

    print("SANITY CHECK - top 8 skills by mean proficiency, per class")
    for cls in sorted(df["career_path"].unique()):
        sub = df[df["career_path"] == cls][scols].mean().sort_values(ascending=False)[:8]
        top = ", ".join(s.replace("skill_", "") for s in sub.index)
        print(f"  {cls:<24} {top}")
    print("=" * 68)


